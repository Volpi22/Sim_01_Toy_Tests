"""
=============================================================================
LSTM Ablation & Latent Space Visualizer
=============================================================================
This script proves that the DRQN agent relies on its recurrent temporal 
memory (LSTM) to safely navigate pharmacodynamics, rather than acting as a 
purely reactive network.

Usage Example:
--------------
    python model_study.py Glioblastoma

Prerequisites:
--------------
    1. A trained champion model saved as: models/<Cancer_Name>_drqn_best.pt
    2. A completed 100-patient evaluation CSV generated by evaluate.py, saved 
       as: results/<Cancer_Name>_frozen_metrics_summary.csv
       (This saves compute time by loading the intact baseline directly).

Outputs:
--------------
    - results/<Cancer_Name>_ablation_chart.png (Bar chart proving memory utility)
    - results/<Cancer_Name>_pca_trajectory.png (2D Geometric map of the agent's brain)
=============================================================================
"""

import os
import sys
import torch
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA

# Import your existing environment and model classes
from environment import PredictiveChemoEnv
from train import DRQN, CANCER_PROFILES

def run_ablation_study(cancer_name, model_path, data_path, num_episodes=100):
    print(f"\n{'='*80}")
    print(f" RUNNING ZERO-MEMORY ABLATION STUDY: {cancer_name}")
    print(f"{'='*80}")
    
    csv_path = f"results/{cancer_name}_frozen_metrics_summary.csv"
    if not os.path.exists(csv_path):
        print(f"[ERROR] Baseline CSV not found at {csv_path}.")
        print("Please run 'python evaluate.py --cancer {cancer_name} --frozen' first.")
        return
        
    # 1. Load Intact Baseline directly from your existing evaluation CSV
    df = pd.read_csv(csv_path)
    baseline_row = df[df['Scenario'] == 'Medium Growth (Typical)'].iloc[0]
    
    results = {}
    results["Intact LSTM (Loaded)"] = {
        "Accuracy": baseline_row["Accuracy (%)"],
        "MHR": baseline_row["MHR (%)"],
        "MAT": baseline_row["MAT"],
        "MER": baseline_row["MER"]
    }
    
    print(f"Successfully loaded Intact Baseline (Accuracy: {results['Intact LSTM (Loaded)']['Accuracy']}%) from CSV.")

    # 2. Simulate the Ablated (Zero-Memory) Agent
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = DRQN(input_dim=64, num_actions=10).to(device)
    model.load_state_dict(torch.load(model_path, map_location=device, weights_only=True))
    model.eval()

    env = PredictiveChemoEnv(
        schedule_parquet_path=data_path, 
        drug_name=CANCER_PROFILES[cancer_name]['drug'], 
        tumor_zone=CANCER_PROFILES[cancer_name]['zone']
    )

    print(f"\nRunning 100 patients with: Ablated Memory (Zeroed)...")
    survivals, mhr_list, mat_list, returns = [], [], [], []

    obs, _ = env.reset(seed=42)
    ABSOLUTE_BASE_K_ELIM = env.engine.drug['k_elim']
    ABSOLUTE_BASE_THRESHOLD = env.critical_toxicity_threshold

    for ep_idx in range(num_episodes):
        obs, _ = env.reset(seed=42 + ep_idx)
        
        # Reset to typical baseline
        env.engine.drug['k_elim'] = ABSOLUTE_BASE_K_ELIM
        env.critical_toxicity_threshold = ABSOLUTE_BASE_THRESHOLD
        env.engine.tumor_growth_rate = 0.025
        env.is_resistant = False 

        initial_distance = env.prev_distance
        total_reward = 0.0
        terminated, truncated = False, False
        max_tox = 0.0
        
        while not (terminated or truncated):
            obs_tensor = torch.FloatTensor(obs).view(1, 1, -1).to(device)
            
            with torch.no_grad():
                # The Ablation: We ask the network for a Q-value, but we NEVER update the hidden state.
                # It is perpetually stuck at 'None' (zeros), forcing a purely reactive decision.
                q_vals, _ = model(obs_tensor, None)
                action = q_vals[0, 0, :].argmax().item()
                
            obs, reward, terminated, truncated, info = env.step(action)
            total_reward += reward
            max_tox = max(max_tox, env.total_toxicity)
            final_distance = info['curr_dist']
            survived = info['survived']
            
        mhr = max(0.0, ((initial_distance - final_distance) / initial_distance) * 100.0)
        
        survivals.append(1 if survived else 0)
        mhr_list.append(mhr)
        mat_list.append(max_tox)
        returns.append(total_reward)
        
    results["Ablated LSTM (Simulated)"] = {
        "Accuracy": np.mean(survivals) * 100,
        "MHR": np.mean(mhr_list),
        "MAT": np.mean(mat_list),
        "MER": np.mean(returns)
    }

    # 3. Plot the comparative bar chart
    modes = list(results.keys())
    labels = list(results[modes[0]].keys())
    intact_vals = list(results[modes[0]].values())
    ablated_vals = list(results[modes[1]].values())

    x = np.arange(len(labels))
    width = 0.35

    # Switch to default (white) background
    plt.style.use('default')
    fig, ax = plt.subplots(figsize=(10, 6))
    
    rects1 = ax.bar(x - width/2, intact_vals, width, label='Intact LSTM (Predictive)', color='#3b82c4')
    rects2 = ax.bar(x + width/2, ablated_vals, width, label='Ablated LSTM (Reactive)', color='#f09436')

    ax.set_ylabel('Scores / Percentages')
    ax.set_title(f'Ablation Study: Impact of Temporal Memory on Clinical Outcomes\n({cancer_name})', fontweight='bold')
    ax.set_xticks(x)
    ax.set_xticklabels(labels)
    ax.legend()
    
    # Add a subtle grid for better readability on white
    ax.grid(axis='y', linestyle='--', alpha=0.5, color='gray')

    os.makedirs("results", exist_ok=True)
    plt.savefig(f"results/{cancer_name}_ablation_chart.png", dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved Ablation Chart to results/{cancer_name}_ablation_chart.png")

def plot_pca_latent_space(cancer_name, model_path, data_path):
    print(f"\n{'='*80}")
    print(f" MAPPING LSTM LATENT SPACE (PCA): {cancer_name}")
    print(f"{'='*80}")
    
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = DRQN(input_dim=64, num_actions=10).to(device)
    model.load_state_dict(torch.load(model_path, map_location=device, weights_only=True))
    model.eval()

    env = PredictiveChemoEnv(
        schedule_parquet_path=data_path, 
        drug_name=CANCER_PROFILES[cancer_name]['drug'], 
        tumor_zone=CANCER_PROFILES[cancer_name]['zone']
    )

    obs, _ = env.reset(seed=42) # Use a single seed to plot one complete trajectory
    hidden = None
    terminated, truncated = False, False
    
    cell_states = []
    toxicities = []
    time_steps = []

    while not (terminated or truncated):
        obs_tensor = torch.FloatTensor(obs).view(1, 1, -1).to(device)
        with torch.no_grad():
            q_vals, hidden = model(obs_tensor, hidden)
            action = q_vals[0, 0, :].argmax().item()
            
            # hidden is a tuple of (h_t, c_t). We want the long-term cell state c_t.
            # Shape is (1, 1, 128). Squeeze to get a flat 128-dim vector.
            c_t = hidden[1].squeeze().cpu().numpy()
            cell_states.append(c_t)
            
        obs, _, terminated, truncated, _ = env.step(action)
        
        toxicities.append(env.total_toxicity)
        time_steps.append(env.current_step)

    # Apply PCA to reduce 128 dimensions down to 2
    pca = PCA(n_components=2)
    pca_result = pca.fit_transform(cell_states)
    
    pca_x = pca_result[:, 0]
    pca_y = pca_result[:, 1]
    
    # Switch to default (white) background
    plt.style.use('default')
    fig, ax = plt.subplots(figsize=(10, 8))
    
    # Create a scatter plot colored by the accumulated toxicity
    # Changed edgecolor to black for contrast against white background
    scatter = ax.scatter(pca_x, pca_y, c=toxicities, cmap='inferno', s=50, edgecolor='black', linewidth=0.5)
    
    # Draw arrows to show the direction of time/trajectory
    for i in range(0, len(pca_x)-1, 5):  # Add an arrow every 5 steps
        # Changed arrow color to black
        ax.annotate('', xy=(pca_x[i+1], pca_y[i+1]), xytext=(pca_x[i], pca_y[i]),
                    arrowprops=dict(arrowstyle="->", color="black", alpha=0.6))

    # Highlight Start and End points (added black edgecolors so they stand out)
    ax.scatter(pca_x[0], pca_y[0], color='lime', s=200, marker='*', edgecolor='black', label='Infusion Start (T=0)', zorder=5)
    ax.scatter(pca_x[-1], pca_y[-1], color='cyan', s=200, marker='X', edgecolor='black', label='Infusion End (T=240)', zorder=5)

    cbar = plt.colorbar(scatter, ax=ax)
    cbar.set_label('Systemic Accumulated Toxicity')
    
    ax.set_title(f'LSTM Long-Term Memory (Cell State) Trajectory via PCA\n{cancer_name}', fontweight='bold', fontsize=14)
    ax.set_xlabel(f'Principal Component 1 ({pca.explained_variance_ratio_[0]*100:.1f}% Variance)')
    ax.set_ylabel(f'Principal Component 2 ({pca.explained_variance_ratio_[1]*100:.1f}% Variance)')
    ax.legend()
    
    # Lighter dashed grid for white background
    ax.grid(True, alpha=0.4, color='gray', linestyle='--')

    os.makedirs("results", exist_ok=True)
    plt.savefig(f"results/{cancer_name}_pca_trajectory.png", dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved PCA Trajectory to results/{cancer_name}_pca_trajectory.png")

if __name__ == "__main__":
    target_cancer = sys.argv[1] if len(sys.argv) > 1 else "Glioblastoma"
    model_file = f"models/{target_cancer}_drqn_best.pt"
    data_file = "datasets/1_week_sampling_schedule.parquet"
    
    if not os.path.exists(model_file):
        print(f"[ERROR] Could not find {model_file}. Did you train and rename the champion model?")
    else:
        run_ablation_study(target_cancer, model_file, data_file, num_episodes=100)
        plot_pca_latent_space(target_cancer, model_file, data_file)